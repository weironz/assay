    def test_failed_agent_validation_restores_managed_bytes_and_reopens_web(self):
        with tempfile.TemporaryDirectory() as directory:
            root=Path(directory);ad=root/'ad';managed=ad/'etc/assay';managed.mkdir(parents=True)
            before=b'# Managed by Assay Samba Agent. Do not edit this file.\n\n[test]\n    recycle:maxsize = 0\n'
            path=managed/'shares.conf';path.write_bytes(before);(managed/'shares.json').write_bytes(b'[]')
            backup=root/'backup/ad/etc/assay';backup.mkdir(parents=True);(backup/'shares.conf').write_bytes(before)
            (root/'agent.json').write_text(json.dumps({'config_dir':'/managed','samba_config_file_name':'shares.conf','shares_file_name':'shares.json'}))
            operation=root/'operation';operation.mkdir()
            calls=[]
            def agent(endpoint,*args):
                calls.append(endpoint)
                if endpoint=='/v1/snapshot':return {'groups':[dict(name='team',id='stable-id',revision='revision')]}
                if len(calls)==2:raise urllib.error.HTTPError('http://agent',400,'Conflict',{},io.BytesIO(json.dumps({'error':'managed config changed outside Agent; reconcile manually'}).encode()))
                self.assertIn(b'recycle:touch_mtime = yes',path.read_bytes())
                raise RuntimeError('Other setting differs from the Rust renderer')
            host=SimpleNamespace(root=root,ad_root=ad,operation=operation,p={'deployedImageIds':{},'previewGroup':'team','backup':str(root/'backup')},
                image_ids=lambda:{},agent=agent,items={'agent':{'Mounts':[{'Destination':'/managed','Source':str(managed)}]}},ad={'Id':'ad'},compose=['compose'])
            with patch.object(maintenance,'run') as run:
                with self.assertRaisesRegex(RuntimeError,'Other setting'):maintenance.Company.reconcile(host)
            self.assertEqual(path.read_bytes(),before)
            self.assertEqual((managed/'shares.json').read_bytes(),b'[]')
            self.assertEqual(run.call_args_list[-1].args,('compose','start','web'))

    def test_managed_template_migration_is_narrow_idempotent_and_preserves_other_settings(self):
        before=b'# Managed by Assay Samba Agent. Do not edit this file.\n\n[test]\n    path = /shares/original\n    valid users = @EXAMPLE\\team\n    recycle:maxsize = 0\n'
        after,names=maintenance.legacy_managed_candidate(before)
        self.assertEqual(names,['test'])
        self.assertEqual(after,before+b'    recycle:touch_mtime = yes\n')
        self.assertEqual(maintenance.legacy_managed_candidate(after),(after,[]))
        explicit=before+b'    recycle:touch_mtime = no\n'
        self.assertEqual(maintenance.legacy_managed_candidate(explicit),(explicit,[]))
        for invalid in (before.replace(b'# Managed by Assay Samba Agent.',b'# Manual settings.'),before.replace(b'maxsize = 0',b'maxsize = 4096')):
            with self.assertRaises(AssertionError):maintenance.legacy_managed_candidate(invalid)

    def test_rename_overlay_keeps_ids_aliases_and_excluded_shares(self):
        source=b'[finance]\n valid users = @EXAMPLE\\finance\n vfs objects = recycle\n[common]\n valid users = @EXAMPLE\\common\n'
        catalog={'aliases':{'old_team':'finance'},'external':[{'id':'stable-guid','name':'finance','path':'old-path','groups':['finance']},{'id':'public','name':'common','groups':['common']}]}
        extra,full,selected=maintenance.overlay_policy(json.dumps(catalog).encode(),source,['finance'],'EXAMPLE','company_leadership')
        self.assertEqual(selected,['finance'])
        self.assertEqual(extra['aliases'],catalog['aliases'])
        self.assertEqual(extra['external'][0]['id'],'stable-guid')
        self.assertEqual(extra['external'][0]['path'],'old-path')
        self.assertEqual(extra['external'][1],catalog['external'][1])
        self.assertIn('company_leadership',extra['external'][0]['groups'])
        self.assertIn(b'acl_xattr recycle',full)
        self.assertEqual(full.split(b'[common]')[1],source.split(b'[common]')[1])
        blocked=maintenance.maintenance_admission(full,selected,'EXAMPLE\\service')
        self.assertIn(b'valid users = "EXAMPLE\\service"',blocked)
        self.assertNotIn(b'company_leadership',blocked)
        self.assertEqual(maintenance.overlay_policy(json.dumps(extra).encode(),full,['finance'],'EXAMPLE','company_leadership')[1],full)

    def test_runtime_qualification_rejects_application_changes_and_mismatched_release(self):
        with tempfile.TemporaryDirectory() as directory:
            state=Path(directory);(state/'dist').mkdir()
            identity=dict(commit='original',sourceSha256='digest',version='1.0.0')
            images={k:{'imageId':k,'digest':'digest-'+k} for k in ('api','web','samba-agent')}
            ids={k:v['imageId'] for k,v in images.items()}
            verified={**identity,'imageIds':ids,'assets':{}}
            backup={**identity,'host':'host','directory':'/data/assay','proof':dict(completed=True,restoreVerified=True,backup='/backup',imageIds={'api':'old-api','web':'old-web'})}
            deployed={**identity,'host':'host','directory':'/data/assay','proof':dict(completed=True,dataPreserved=True,localAttachmentsPreserved=True,backup='/backup',imageIds=ids)}
            values={'release':{**identity,'images':images},'verified':verified,'upgrade':{**identity,'preserved':True,'rollbackCompatible':True,'targetImageIds':ids,'sourceImages':backup['proof']['imageIds']},'company-backup':backup,'company-deployed':deployed}
            for name,value in values.items():(state/(name+'.json')).write_text(json.dumps(value))
            manifest={**identity,'images':images,'assets':{},'verification':verified}
            (state/'dist/release-manifest.json').write_text(json.dumps(manifest))
            ci=SimpleNamespace(state=state,version='1.0.0',receipt=lambda _:None)
            with patch.object(company.subprocess,'check_output',return_value=''):
                self.assertEqual(company.published_runtime(ci,'host','/data/assay')['artifactSourceCommit'],'original')
            with patch.object(company.subprocess,'check_output',return_value='docs/runbook.md\0'):
                self.assertEqual(company.published_runtime(ci,'host','/data/assay')['releaseImageIds'],ids)
                (state/'company-deployed.json').unlink()
                recovered=company.published_runtime(ci,'host','/data/assay',recovering=True)
                self.assertEqual(recovered['images'],images)
                self.assertNotIn('deployedImageIds',recovered)
                (state/'company-deployed.json').write_text(json.dumps(deployed))
                with self.assertRaisesRegex(RuntimeError,'another target'):company.published_runtime(ci,'wrong','/data/assay')
                deployed['proof']['imageIds']={'api':'wrong'}
                (state/'company-deployed.json').write_text(json.dumps(deployed))
                with self.assertRaisesRegex(RuntimeError,'preservation proof'):company.published_runtime(ci,'host','/data/assay')
            with patch.object(company.subprocess,'check_output',return_value='agents/samba/src/main.rs\0'):
                with self.assertRaisesRegex(RuntimeError,'Application source changed'):company.published_runtime(ci,'host','/data/assay')

    def test_controller_recovery_requires_matching_completed_remote_proof(self):
        with tempfile.TemporaryDirectory() as directory:
            c=object.__new__(maintenance.Company);c.root=Path(directory)
            prior=c.root/'rollback/task-deploy-20261111T100401Z-abcdef';prior.mkdir(parents=True)
            images={k:{'imageId':'config-'+k,'digest':'manifest-'+k} for k in ('api','web','samba-agent')}
            ids={k:v['imageId'] for k,v in images.items()};live={k:v['digest'] for k,v in images.items()}
            old=dict(action='deploy',directory=str(c.root),version='1.0.0',backup='/backup',sourceImageIds={'api':'old'},images=images)
            proof=dict(action='deploy',directory=str(c.root),version='1.0.0',backup='/backup',imageIds=ids,runtimeImageIds=live,completed=True,dataPreserved=True,localAttachmentsPreserved=True,sambaUnchanged=True)
            (prior/'parameters.json').write_text(json.dumps(old))
            c.p={**old,'resumeOperation':str(prior),'releaseImageIds':ids}
            with patch.object(c,'runtime',return_value={'runtimeHealthy':True}) as checked:
                with self.assertRaisesRegex(AssertionError,'not completed'):c.resume()
                checked.assert_not_called()
                for change in ({'dataPreserved':False},{'runtimeImageIds':{'api':'wrong'}},{'version':'wrong'},{'backup':'/wrong'},{'completed':False}):
                    (prior/'result.json').write_text(json.dumps({**proof,**change}))
                    with self.assertRaises(AssertionError):c.resume()
                    checked.assert_not_called()
                (prior/'result.json').write_text(json.dumps(proof))
                result=c.resume()
                self.assertTrue(result['deploymentDataPreserved'])
                self.assertEqual(c.p['deployedImageIds'],live)
                checked.assert_called_once()
                c.p['images']={**images,'unapproved':{}}
                with self.assertRaisesRegex(AssertionError,'parameters differ'):c.resume()

