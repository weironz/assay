use crate::{ad, config::Config};
use anyhow::{Result, ensure};
use cap_fs_ext::DirExt;
use cap_std::{ambient_authority, fs::Dir};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use std::{fs, io::Write, os::unix::fs::PermissionsExt, path::Path};
use tokio::{
    io::{AsyncBufReadExt, AsyncReadExt, AsyncWriteExt, BufReader},
    net::{UnixListener, UnixStream},
};

#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Share {
    pub name: String,
    pub comment: String,
    pub groups: Vec<String>,
    pub read_only: bool,
    #[serde(default)]
    pub ready: bool,
    #[serde(default = "active_default")]
    pub active: bool,
}
fn active_default() -> bool {
    true
}
#[derive(Serialize, Deserialize)]
#[serde(
    tag = "action",
    content = "args",
    rename_all = "snake_case",
    deny_unknown_fields
)]
pub enum Local {
    List,
    Save(Share),
    Remove { name: String },
    Directories { share: String, path: String },
}
pub fn components(path: &str) -> Result<Vec<&str>> {
    ensure!(
        path.len() <= 1024 && !path.contains(['\\', '\0', ':']) && !path.starts_with('/'),
        "invalid relative path"
    );
    if path.is_empty() {
        return Ok(vec![]);
    }
    let parts = path.split('/').collect::<Vec<_>>();
    ensure!(
        parts.len() <= 16
            && parts.iter().all(|p| !p.is_empty()
                && *p != "."
                && *p != ".."
                && p.len() <= 128
                && !p.chars().any(char::is_control)),
        "path traversal rejected"
    );
    Ok(parts)
}
fn dir(c: &Config, share: &str, path: &str) -> Result<Dir> {
    ad::name(share)?;
    let mut d =
        Dir::open_ambient_dir(&c.shares_root, ambient_authority())?.open_dir_nofollow(share)?;
    for part in components(path)? {
        d = d.open_dir_nofollow(part)?;
    }
    Ok(d)
}
fn render(c: &Config, shares: &[Share]) -> Result<String> {
    ensure!(
        c.smb_username
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || ['_', '-', '\\'].contains(&c)),
        "invalid SMB service identity"
    );
    let domain = c.smb_username.split('\\').next().unwrap_or_default();
    let mut out = String::from("# Managed by Assay Samba Agent. Do not edit this file.\n");
    for s in shares.iter().filter(|s| s.active) {
        ad::name(&s.name)?;
        ad::text(&s.comment)?;
        ensure!(s.groups.len() <= 100, "too many groups");
        for g in &s.groups {
            ad::name(g)?;
        }
        let users = s
            .groups
            .iter()
            .map(|g| format!("@\"{domain}\\{g}\""))
            .collect::<Vec<_>>()
            .join(" ");
        out += &format!(
            "\n[{}]\n    path = /shares/{}\n    comment = {}\n    browseable = yes\n    read only = {}\n    valid users = \"{}\" {}\n    admin users = \"{}\"\n    vfs objects = acl_xattr\n    acl_xattr:ignore system acls = yes\n    map acl inherit = yes\n    inherit acls = yes\n    wide links = no\n",
            s.name,
            s.name,
            s.comment,
            if s.read_only { "yes" } else { "no" },
            c.smb_username,
            users,
            c.smb_username
        );
    }
    Ok(out)
}
fn atomic(path: &Path, bytes: &[u8]) -> Result<()> {
    let temp = path.with_extension(format!("{}.tmp", uuid::Uuid::new_v4()));
    let mut f = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temp)?;
    f.write_all(bytes)?;
    f.sync_all()?;
    fs::rename(&temp, path)?;
    fs::File::open(path.parent().unwrap())?.sync_all()?;
    Ok(())
}
fn shares(c: &Config) -> Result<Vec<Share>> {
    let p = c.config_dir.join("assay-shares.json");
    if !p.exists() {
        return Ok(vec![]);
    }
    Ok(serde_json::from_slice(&fs::read(p)?)?)
}
fn save(c: &Config, s: &[Share]) -> Result<()> {
    let target = c.config_dir.join("assay-shares.conf");
    if target.exists() {
        ensure!(
            fs::read_to_string(&target)? == render(c, &shares(c)?)?,
            "managed config changed outside Agent; reconcile manually"
        );
    }
    // Reload PID is fixed by deployment, never supplied by an HTTP request.
    let pid = fs::read_to_string(&c.smb_pid_file)?.trim().parse::<i32>()?;
    ensure!(pid > 1, "invalid smbd process");
    let comm = fs::read_to_string(format!("/proc/{pid}/comm"))?;
    ensure!(comm.trim() == "smbd", "configured process is not smbd");
    atomic(&target, render(c, s)?.as_bytes())?;
    nix::sys::signal::kill(
        nix::unistd::Pid::from_raw(pid),
        nix::sys::signal::Signal::SIGHUP,
    )?;
    atomic(
        &c.config_dir.join("assay-shares.json"),
        &serde_json::to_vec(s)?,
    )?;
    Ok(())
}
fn execute(c: &Config, cmd: Local) -> Result<Value> {
    let mut rows = shares(c)?;
    match cmd {
        Local::List => Ok(json!(rows)),
        Local::Save(s) => {
            ad::name(&s.name)?;
            ad::text(&s.comment)?;
            if let Some(i) = rows.iter().position(|r| r.name == s.name) {
                rows[i] = s.clone();
            } else {
                let root = Dir::open_ambient_dir(&c.shares_root, ambient_authority())?;
                ensure!(
                    root.symlink_metadata(&s.name).is_err(),
                    "existing directory requires explicit adoption; not overwriting"
                );
                root.create_dir(&s.name)?;
                root.set_permissions(
                    &s.name,
                    cap_std::fs::Permissions::from_std(fs::Permissions::from_mode(0o777)),
                )?;
                rows.push(s.clone());
            }
            save(c, &rows)?;
            Ok(json!(s))
        }
        Local::Remove { name } => {
            ad::name(&name)?;
            ensure!(rows.iter().any(|r| r.name == name), "share is not managed");
            for row in &mut rows {
                if row.name == name {
                    row.active = false;
                }
            }
            save(c, &rows)?;
            Ok(json!({"removed":true,"filesPreserved":true}))
        }
        Local::Directories { share, path } => {
            ensure!(
                rows.iter().any(|r| r.name == share && r.active),
                "share is not managed"
            );
            let d = dir(c, &share, &path)?;
            let mut children = vec![];
            for e in d.entries()? {
                let e = e?;
                let ft = e.file_type()?;
                if ft.is_dir() {
                    children.push(e.file_name().to_string_lossy().to_string());
                }
            }
            children.sort();
            Ok(json!({"share":share,"path":path,"directories":children}))
        }
    }
}
pub async fn call(c: &Config, cmd: Local) -> Result<Value> {
    let mut stream = UnixStream::connect(&c.helper_socket).await?;
    stream.write_all(&serde_json::to_vec(&cmd)?).await?;
    stream.write_all(b"\n").await?;
    let mut line = String::new();
    BufReader::new(stream).read_line(&mut line).await?;
    let v: Value = serde_json::from_str(&line)?;
    ensure!(
        v["ok"].as_bool() == Some(true),
        "{}",
        v["error"].as_str().unwrap_or("local operation failed")
    );
    Ok(v["result"].clone())
}
pub async fn helper(c: Config) -> Result<()> {
    if c.helper_socket.exists() {
        fs::remove_file(&c.helper_socket)?;
    }
    let listener = UnixListener::bind(&c.helper_socket)?;
    fs::set_permissions(&c.helper_socket, fs::Permissions::from_mode(0o666))?;
    loop {
        let (stream, _) = listener.accept().await?;
        if stream.peer_cred()?.uid() != 10001 {
            continue;
        }
        let mut reader = BufReader::new(stream.take(16385));
        let mut line = Vec::new();
        let read = tokio::time::timeout(
            std::time::Duration::from_secs(5),
            reader.read_until(b'\n', &mut line),
        )
        .await;
        if read.is_err() || line.len() > 16384 || line.last() != Some(&b'\n') {
            continue;
        }
        let result = serde_json::from_slice::<Local>(&line)
            .map_err(anyhow::Error::from)
            .and_then(|cmd| {
                ensure!(
                    !c.read_only || matches!(cmd, Local::List | Local::Directories { .. }),
                    "agent is read-only"
                );
                execute(&c, cmd)
            });
        let v = match result {
            Ok(v) => json!({"ok":true,"result":v}),
            Err(e) => json!({"ok":false,"error":e.to_string()}),
        };
        let mut stream = reader.into_inner().into_inner();
        stream.write_all(&serde_json::to_vec(&v)?).await?;
        stream.write_all(b"\n").await?;
    }
}
