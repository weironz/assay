#[derive(Clone, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Share {
    #[serde(default)]
    pub id: String,
    #[serde(default)]
    pub revision: String,
    pub name: String,
    pub comment: String,
    pub groups: Vec<String>,
    pub read_only: bool,
    #[serde(default)]
    pub ready: bool,
    #[serde(default = "active_default")]
    pub active: bool,
    #[serde(default)]
    pub external: bool,
    #[serde(default)]
    pub path: String,
    #[serde(default = "active_default")]
    pub browseable: bool,
}
#[derive(Deserialize)]
#[serde(deny_unknown_fields)]
struct ExternalShares {
    config_sha256: String,
    shares: Vec<Share>,
}
fn active_default() -> bool {
    true
}
#[derive(Serialize, Deserialize)]
#[serde(
    tag = "action",
    content = "args",
    rename_all = "snake_case",
    deny_unknown_fields
)]
pub enum Local {
    List,
    Save(Share),
    Remove { name: String },
    Directories { share: String, path: String },
}
pub fn components(path: &str) -> Result<Vec<&str>> {
    ensure!(
        path.len() <= 1024 && !path.contains(['\\', '\0', ':']) && !path.starts_with('/'),
        "invalid relative path"
    );
    if path.is_empty() {
        return Ok(vec![]);
    }
    let parts = path.split('/').collect::<Vec<_>>();
    ensure!(
        parts.len() <= 16
            && parts.iter().all(|p| !p.is_empty()
                && *p != "."
                && *p != ".."
                && p.len() <= 128
                && !p.chars().any(char::is_control)),
        "path traversal rejected"
    );
    Ok(parts)
}
fn dir(c: &Config, rows: &[Share], share: &str, path: &str) -> Result<Dir> {
    ad::name(share)?;
    let row = rows
        .iter()
        .find(|row| row.name == share && row.active)
        .ok_or_else(|| anyhow::anyhow!("share is not registered"))?;
    let relative = if row.path.is_empty() {
        &row.name
    } else {
        &row.path
    };
    let mut d = Dir::open_ambient_dir(&c.shares_root, ambient_authority())?;
    for part in components(relative)?.into_iter().chain(components(path)?) {
        d = d.open_dir_nofollow(part)?;
    }
    Ok(d)
}
pub(crate) fn render(c: &Config, shares: &[Share]) -> Result<String> {
    ensure!(
        c.smb_username
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || ['_', '-', '\\'].contains(&c)),
        "invalid SMB service identity"
    );
    let domain = c.smb_username.split('\\').next().unwrap_or_default();
    let mut out = String::from("# Managed by Assay Samba Agent. Do not edit this file.\n");
    for s in shares.iter().filter(|s| s.active && !s.external) {
        ad::name(&s.name)?;
        ensure!(
            !["global", "homes", "printers", "ipc$", "print$"].contains(&s.name.as_str()),
            "protected share name"
        );
        ad::text(&s.comment)?;
        ensure!(s.groups.len() <= 100, "too many groups");
        for g in &s.groups {
            ad::name(g)?;
        }
        let users = s
            .groups
            .iter()
            .map(|g| format!("@\"{domain}\\{g}\""))
            .collect::<Vec<_>>()
            .join(" ");
        let relative = if s.path.is_empty() { &s.name } else { &s.path };
        components(relative)?;
        // access based share enum：无权限用户在枚举中看不到该共享；
        // hide unreadable：目录内不可读条目对无权用户隐藏（ABE）。
        // vfs_recycle：删除进入共享根下隐藏的 .recycle 目录，保留目录结构
        // 与历史版本。可选清理器按首次收录时间保留，不随共享移除删除。
        out += &format!(
            "\n[{}]\n    path = {}/{}\n    comment = {}\n    browseable = {}\n    read only = {}\n    valid users = \"{}\" {}\n    admin users = \"{}\"\n    vfs objects = acl_xattr recycle\n    acl_xattr:ignore system acls = yes\n    map acl inherit = yes\n    inherit acls = yes\n    wide links = no\n    access based share enum = yes\n    hide unreadable = yes\n    recycle:repository = .recycle\n    recycle:keeptree = yes\n    recycle:versions = yes\n    recycle:maxsize = 0\n    recycle:touch_mtime = yes\n",
            s.name,
            c.samba_shares_root.display(),
            relative,
            s.comment,
            if s.browseable { "yes" } else { "no" },
            if s.read_only { "yes" } else { "no" },
            c.smb_username,
            users,
            c.smb_username
        );
    }
    Ok(out)
}
pub(crate) fn atomic(path: &Path, bytes: &[u8]) -> Result<()> {
    struct Temporary(std::path::PathBuf);
    impl Drop for Temporary {
        fn drop(&mut self) {
            let _ = fs::remove_file(&self.0);
        }
    }
    let temp = path.with_extension(format!("{}.tmp", uuid::Uuid::new_v4()));
    let mut f = fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&temp)?;
    let _cleanup = Temporary(temp.clone());
    f.write_all(bytes)?;
    f.sync_all()?;
    fs::rename(&temp, path)?;
    fs::File::open(path.parent().unwrap())?.sync_all()?;
    Ok(())
}
pub(crate) fn shares(c: &Config) -> Result<Vec<Share>> {
    let p = c.config_dir.join(&c.shares_file_name);
    let mut rows: Vec<Share> = if p.exists() {
        serde_json::from_slice(&fs::read(p)?)?
    } else {
        vec![]
    };
    ensure!(
        rows.iter()
            .all(|s| !s.external && components(&s.path).is_ok()),
        "invalid managed share inventory"
    );
    if let (Some(inventory), Some(config)) =
        (&c.external_shares_file, &c.external_samba_config_file)
    {
        let external: ExternalShares = serde_json::from_slice(&fs::read(inventory)?)?;
        ensure!(
            external.config_sha256 == format!("{:x}", Sha256::digest(fs::read(config)?)),
            "existing Samba configuration changed; refresh external share inventory"
        );
        for mut row in external.shares {
            ad::name(&row.name)?;
            ensure!(
                !row.path.is_empty() && !components(&row.path)?.is_empty(),
                "external share path required"
            );
            ensure!(
                !rows.iter().any(|s| s.name == row.name),
                "duplicate share name"
            );
            row.external = true;
            rows.push(row);
        }
    }
    crate::rename::catalog(c, rows)
}
pub(crate) fn reload_pid(c: &Config) -> Result<i32> {
    if !c.reload_via_proc {
        return Ok(fs::read_to_string(&c.smb_pid_file)?.trim().parse()?);
    }
    let mut masters = vec![];
    for entry in fs::read_dir("/proc")? {
        let entry = entry?;
        let Ok(pid) = entry.file_name().to_string_lossy().parse::<i32>() else {
            continue;
        };
        if fs::read_to_string(entry.path().join("comm"))
            .unwrap_or_default()
            .trim()
            != "smbd"
        {
            continue;
        }
        let status = fs::read_to_string(entry.path().join("status"))?;
        let parent = status
            .lines()
            .find_map(|line| line.strip_prefix("PPid:"))
            .and_then(|value| value.trim().parse::<i32>().ok())
            .ok_or_else(|| anyhow::anyhow!("smbd parent unavailable"))?;
        let parent_name = fs::read_to_string(format!("/proc/{parent}/comm"))?;
        if !parent_name.trim().starts_with("smbd") {
            masters.push(pid);
        }
    }
    ensure!(
        masters.len() == 1,
        "exactly one smbd master required in the shared PID namespace"
    );
    Ok(masters[0])
}
fn save(c: &Config, s: &[Share]) -> Result<()> {
    if c.rename.is_some() {
        return crate::rename::save_catalog(c, s);
    }
    let target = c.config_dir.join(&c.samba_config_file_name);
    if target.exists() {
        ensure!(
            fs::read_to_string(&target)? == render(c, &shares(c)?)?,
            "managed config changed outside Agent; reconcile manually"
        );
    }
    // Reload PID is fixed by deployment, never supplied by an HTTP request.
    let pid = reload_pid(c)?;
    ensure!(pid > 1, "invalid smbd process");
    let comm = fs::read_to_string(format!("/proc/{pid}/comm"))?;
    ensure!(comm.trim() == "smbd", "configured process is not smbd");
    atomic(&target, render(c, s)?.as_bytes())?;
    nix::sys::signal::kill(
        nix::unistd::Pid::from_raw(pid),
        nix::sys::signal::Signal::SIGHUP,
    )?;
    atomic(
        &c.config_dir.join(&c.shares_file_name),
        &serde_json::to_vec(&s.iter().filter(|s| !s.external).collect::<Vec<_>>())?,
    )?;
    Ok(())
}
fn execute(c: &Config, cmd: Local) -> Result<Value> {
    let mut rows = shares(c)?;
    match cmd {
        Local::List => Ok(json!(rows)),
        Local::Save(s) => {
            ensure!(
                !["global", "homes", "printers", "ipc$", "print$"].contains(&s.name.as_str()),
                "protected share name"
            );
            ensure!(
                !s.external && s.path.is_empty(),
                "external share definitions are deployment-owned"
            );
            ad::name(&s.name)?;
            ad::text(&s.comment)?;
            if let Some(i) = rows.iter().position(|r| r.name == s.name) {
                ensure!(
                    !rows[i].external,
                    "existing share definition is managed by the Samba configuration"
                );
                let mut updated = s.clone();
                updated.id = rows[i].id.clone();
                updated.path = rows[i].path.clone();
                updated.browseable = rows[i].browseable;
                rows[i] = updated;
            } else {
                let root = Dir::open_ambient_dir(&c.shares_root, ambient_authority())?;
                ensure!(
                    root.symlink_metadata(&s.name).is_err(),
                    "existing directory requires explicit adoption; not overwriting"
                );
                root.create_dir(&s.name)?;
                root.set_permissions(
                    &s.name,
                    cap_std::fs::Permissions::from_std(fs::Permissions::from_mode(0o777)),
                )?;
                rows.push(s.clone());
            }
            save(c, &rows)?;
            Ok(json!(s))
        }
        Local::Remove { name } => {
            ad::name(&name)?;
            ensure!(rows.iter().any(|r| r.name == name), "share is not managed");
            ensure!(
                !rows.iter().any(|r| r.name == name && r.external),
                "existing share definition is managed by the Samba configuration"
            );
            for row in &mut rows {
                if row.name == name {
                    row.active = false;
                }
            }
            save(c, &rows)?;
            Ok(json!({"removed":true,"filesPreserved":true}))
        }
        Local::Directories { share, path } => {
            ensure!(
                rows.iter().any(|r| r.name == share && r.active),
                "share is not managed"
            );
            let d = dir(c, &rows, &share, &path)?;
            let mut children = vec![];
            for e in d.entries()? {
                let e = e?;
                let ft = e.file_type()?;
                if ft.is_dir() {
                    children.push(e.file_name().to_string_lossy().to_string());
                }
            }
            children.sort();
            Ok(json!({"share":share,"path":path,"directories":children}))
        }
    }
}
pub async fn call(c: &Config, cmd: Local) -> Result<Value> {
    let Some(socket) = &c.helper_socket else {
        // Preserve the old helper's serialized execution without another process.
        static LOCK: std::sync::Mutex<()> = std::sync::Mutex::new(());
        ensure!(
            !c.read_only || matches!(cmd, Local::List | Local::Directories { .. }),
            "agent is read-only"
        );
        let c = c.clone();
        return tokio::task::spawn_blocking(move || {
            // Keep the lock inside the blocking task even if its caller disconnects.
            let _guard = LOCK
                .lock()
                .map_err(|_| anyhow::anyhow!("local operation lock poisoned"))?;
            execute(&c, cmd)
        })
        .await?;
    };
    let mut stream = UnixStream::connect(socket).await?;
    stream.write_all(&serde_json::to_vec(&cmd)?).await?;
    stream.write_all(b"\n").await?;
    let mut line = String::new();
    BufReader::new(stream).read_line(&mut line).await?;
    let v: Value = serde_json::from_str(&line)?;
    ensure!(
        v["ok"].as_bool() == Some(true),
        "{}",
        v["error"].as_str().unwrap_or("local operation failed")
    );
    Ok(v["result"].clone())
}
pub async fn helper(c: Config) -> Result<()> {
    let socket = c
        .helper_socket
        .as_ref()
        .ok_or_else(|| anyhow::anyhow!("legacy helper socket required"))?;
    if socket.exists() {
        fs::remove_file(socket)?;
    }
    let listener = UnixListener::bind(socket)?;
    fs::set_permissions(socket, fs::Permissions::from_mode(0o666))?;
    loop {
        let (stream, _) = listener.accept().await?;
        if stream.peer_cred()?.uid() != 10001 {
            continue;
        }
        let mut reader = BufReader::new(stream.take(16385));
        let mut line = Vec::new();
        let read = tokio::time::timeout(
            std::time::Duration::from_secs(5),
            reader.read_until(b'\n', &mut line),
        )
        .await;
        if read.is_err() || line.len() > 16384 || line.last() != Some(&b'\n') {
            continue;
        }
        let result = serde_json::from_slice::<Local>(&line)
            .map_err(anyhow::Error::from)
            .and_then(|cmd| {
                ensure!(
                    !c.read_only || matches!(cmd, Local::List | Local::Directories { .. }),
                    "agent is read-only"
                );
                execute(&c, cmd)
            });
        let v = match result {
            Ok(v) => json!({"ok":true,"result":v}),
            Err(e) => json!({"ok":false,"error":e.to_string()}),
        };
        let mut stream = reader.into_inner().into_inner();
        stream.write_all(&serde_json::to_vec(&v)?).await?;
        stream.write_all(b"\n").await?;
    }
}
